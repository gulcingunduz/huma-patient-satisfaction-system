-- Base tables (idempotent for fresh databases; preserves existing tables and data)
CREATE TABLE IF NOT EXISTS departments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS surveys (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(150) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL
);

CREATE TABLE IF NOT EXISTS staff_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id bigint,
    username varchar(100) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    full_name varchar(120) NOT NULL,
    role varchar(30) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_staff_users_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE IF NOT EXISTS survey_accesses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id bigint NOT NULL,
    department_id bigint NOT NULL,
    public_token_hash varchar(128) NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_survey_accesses_survey FOREIGN KEY (survey_id) REFERENCES surveys(id),
    CONSTRAINT fk_survey_accesses_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE IF NOT EXISTS survey_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id bigint NOT NULL,
    version_number integer NOT NULL,
    status varchar(20) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    published_at timestamp with time zone,
    CONSTRAINT uk_survey_version_number UNIQUE (survey_id, version_number),
    CONSTRAINT fk_survey_versions_survey FOREIGN KEY (survey_id) REFERENCES surveys(id)
);

CREATE TABLE IF NOT EXISTS questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id bigint NOT NULL,
    survey_version_id bigint,
    text varchar(500) NOT NULL,
    type varchar(30) NOT NULL,
    display_order integer NOT NULL,
    required boolean NOT NULL,
    active boolean NOT NULL DEFAULT true,
    scope varchar(30) NOT NULL DEFAULT 'COMMON',
    department_id bigint,
    metric_code varchar(100),
    CONSTRAINT fk_questions_survey FOREIGN KEY (survey_id) REFERENCES surveys(id)
);

CREATE TABLE IF NOT EXISTS survey_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_id bigint NOT NULL,
    department_id bigint NOT NULL,
    survey_version_id bigint,
    client_token_hash varchar(128) NOT NULL,
    tracking_token_hash varchar(128) NOT NULL,
    overall_score numeric(5, 2) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_survey_submissions_survey FOREIGN KEY (survey_id) REFERENCES surveys(id),
    CONSTRAINT fk_survey_submissions_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE IF NOT EXISTS answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL,
    question_id bigint NOT NULL,
    answer_value varchar(2000) NOT NULL,
    score numeric(5, 2),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_answers_submission FOREIGN KEY (submission_id) REFERENCES survey_submissions(id),
    CONSTRAINT fk_answers_question FOREIGN KEY (question_id) REFERENCES questions(id)
);

CREATE TABLE IF NOT EXISTS staff_feedbacks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_user_id bigint NOT NULL,
    submission_id bigint NOT NULL,
    comment varchar(2000) NOT NULL,
    score numeric(5, 2),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_staff_feedbacks_user FOREIGN KEY (staff_user_id) REFERENCES staff_users(id),
    CONSTRAINT fk_staff_feedbacks_submission FOREIGN KEY (submission_id) REFERENCES survey_submissions(id)
);

CREATE TABLE IF NOT EXISTS patient_feedback_evaluations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL,
    staff_user_id bigint NOT NULL,
    status varchar(30) NOT NULL,
    notes varchar(2000),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_pfe_submission FOREIGN KEY (submission_id) REFERENCES survey_submissions(id),
    CONSTRAINT fk_pfe_staff_user FOREIGN KEY (staff_user_id) REFERENCES staff_users(id)
);

CREATE TABLE IF NOT EXISTS feedback_satisfactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL UNIQUE,
    satisfied varchar(20) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_feedback_satisfactions_submission FOREIGN KEY (submission_id) REFERENCES survey_submissions(id)
);

CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_user_id bigint NOT NULL,
    type varchar(30) NOT NULL,
    message varchar(500) NOT NULL,
    read boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_notifications_staff_user FOREIGN KEY (staff_user_id) REFERENCES staff_users(id)
);

CREATE TABLE IF NOT EXISTS ai_summaries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint,
    summary_text varchar(5000) NOT NULL,
    model_name varchar(100) NOT NULL,
    department_id bigint NOT NULL,
    created_by_staff_user_id bigint NOT NULL,
    date_from date NOT NULL,
    date_to date NOT NULL,
    low_score_only boolean NOT NULL DEFAULT false,
    status varchar(20) NOT NULL,
    retry_count integer NOT NULL DEFAULT 0,
    submission_count integer NOT NULL DEFAULT 0,
    error_message varchar(1000),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT fk_ai_summaries_submission FOREIGN KEY (submission_id) REFERENCES survey_submissions(id),
    CONSTRAINT fk_ai_summaries_department FOREIGN KEY (department_id) REFERENCES departments(id),
    CONSTRAINT fk_ai_summaries_creator FOREIGN KEY (created_by_staff_user_id) REFERENCES staff_users(id)
);

-- Additive columns for pre-existing databases
ALTER TABLE questions ADD COLUMN IF NOT EXISTS scope varchar(30);
ALTER TABLE questions ADD COLUMN IF NOT EXISTS department_id bigint;
ALTER TABLE questions ADD COLUMN IF NOT EXISTS metric_code varchar(100);
ALTER TABLE questions ADD COLUMN IF NOT EXISTS survey_version_id bigint;
ALTER TABLE survey_submissions ADD COLUMN IF NOT EXISTS survey_version_id bigint;

UPDATE questions
SET scope = 'COMMON'
WHERE scope IS NULL;

ALTER TABLE questions ALTER COLUMN scope SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_questions_department') THEN
        ALTER TABLE questions
            ADD CONSTRAINT fk_questions_department
                FOREIGN KEY (department_id) REFERENCES departments(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_questions_survey_version') THEN
        ALTER TABLE questions
            ADD CONSTRAINT fk_questions_survey_version
                FOREIGN KEY (survey_version_id) REFERENCES survey_versions(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_survey_submissions_version') THEN
        ALTER TABLE survey_submissions
            ADD CONSTRAINT fk_survey_submissions_version
                FOREIGN KEY (survey_version_id) REFERENCES survey_versions(id);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_question_scope_department') THEN
        ALTER TABLE questions
            ADD CONSTRAINT chk_question_scope_department
                CHECK (
                    (scope = 'COMMON' AND department_id IS NULL)
                    OR
                    (scope = 'DEPARTMENT_SPECIFIC' AND department_id IS NOT NULL)
                );
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_questions_published_department
    ON questions (survey_id, active, scope, department_id, display_order);

CREATE INDEX IF NOT EXISTS idx_survey_submissions_department_created
    ON survey_submissions (department_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_survey_submissions_version
    ON survey_submissions (survey_version_id);
